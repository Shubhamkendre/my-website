function clamp(v, min, max) {
  return Math.max(min, Math.min(max, v));
}

// Progress of an element's own journey through the viewport:
// 0 = its top has just reached the bottom of the screen (about to appear),
// 1 = it has fully scrolled past the top of the screen (fully exited above).
function viewportProgress(el) {
  const rect = el.getBoundingClientRect();
  const vh = window.innerHeight || document.documentElement.clientHeight;
  return clamp((vh - rect.top) / (vh + rect.height), 0, 1);
}

// Walk-in start/end X offsets, in px, relative to each figure's own CSS
// base position (its plain `left`/`right` placement, before any transform).
// Recomputed from actual layout on load/resize so groom & bride always end
// up with a real gap between them — never overlapping — on any screen size,
// instead of relying on one fixed desktop pixel value.
let groomStartX = 0, groomEndX = 0, brideStartX = 0, brideEndX = 0;

function recalcWalkOffsets() {
  // offsetLeft/offsetWidth reflect layout position only — transforms (which
  // is all our scroll animation ever touches) don't affect them, so these
  // are safe to read regardless of the figures' current animated position.
  const stageWidth = stageEl.offsetWidth;
  const groomBaseLeft = groomEl.offsetLeft;
  const groomWidth = groomEl.offsetWidth;
  const brideBaseLeft = brideEl.offsetLeft;

  const center = stageWidth / 2;
  const gap = clamp(stageWidth * 0.07, 18, 90); // breathing room left for the heart

  groomEndX = (center - gap / 2) - (groomBaseLeft + groomWidth);
  brideEndX = (center + gap / 2) - brideBaseLeft;

  groomStartX = -(groomBaseLeft + groomWidth) - 40;   // fully off-screen left
  brideStartX = (stageWidth - brideBaseLeft) + 40;     // fully off-screen right
}

function updateCoupleScroll() {
  const pStage = viewportProgress(stageEl);

  // Groom & bride finish walking in once the stage is roughly centred on
  // screen (pStage ~0.55) rather than waiting for it to scroll away —
  // that keeps the "meeting" moment, and the heart, actually visible.
  const pWalk = clamp(pStage / 0.55, 0, 1);
  const groomX = groomStartX + pWalk * (groomEndX - groomStartX);
  const brideX = brideStartX + pWalk * (brideEndX - brideStartX);
  const walkOpacity = clamp(pWalk * 1.6, 0, 1);

  groomEl.style.transform = `translateX(${groomX}px)`;
  groomEl.style.opacity = walkOpacity;
  brideEl.style.transform = `translateX(${brideX}px)`;
  brideEl.style.opacity = walkOpacity;

  // Heart pops in as they meet, while the stage is still comfortably on screen.
  const heartP = clamp((pStage - 0.35) / 0.2, 0, 1);
  heartEl.style.opacity = heartP;
  heartEl.style.transform = `translate(-50%, -50%) scale(${0.2 + heartP * 0.8})`;

  const pAfter = viewportProgress(afterEl);
  afterEl.style.opacity = clamp(pAfter * 1.4, 0, 1);
}

let couplePlayTicking = false;
function onCoupleScroll() {
  if (!couplePlayTicking) {
    requestAnimationFrame(() => {
      updateCoupleScroll();
      couplePlayTicking = false;
    });
    couplePlayTicking = true;
  }
}

function onCoupleResize() {
  recalcWalkOffsets();
  updateCoupleScroll();
}

