/* --- Keep countdown section height matched to couple section --- */
(function(){
// Keep the countdown section the same overall height as the couple section,
// as requested — measured dynamically so it stays correct across screen
// sizes and once web fonts finish loading (which can reflow text height).
function syncCountdownHeight() {
  const couple = document.getElementById('couple');
  const countdown = document.getElementById('countdown');
  if (!couple || !countdown) return;
  countdown.style.minHeight = couple.offsetHeight + 'px';
}

window.addEventListener('load', syncCountdownHeight);
window.addEventListener('resize', syncCountdownHeight);
if (document.fonts && document.fonts.ready) {
  document.fonts.ready.then(syncCountdownHeight);
}
syncCountdownHeight();

})();

/* --- Gentle 'keep scrolling' hint after the envelope opens --- */
(function(){
const scrollHint = document.getElementById('scroll-hint');
if (scrollHint) {
  let hintDismissed = false;

  function showHintIfReady() {
    if (hintDismissed) return;
    scrollHint.classList.add('show');
  }

  function hideHintOnScroll() {
    if (hintDismissed) return;
    if (window.scrollY > 120) {
      hintDismissed = true;
      scrollHint.classList.remove('show');
    }
  }

  window.addEventListener('scroll', hideHintOnScroll, { passive: true });

  // Reveal shortly after the envelope unlocks the rest of the page.
  if (document.documentElement.classList.contains('envelope-lock')) {
    const observer = new MutationObserver(() => {
      if (!document.documentElement.classList.contains('envelope-lock')) {
        setTimeout(showHintIfReady, 800);
        observer.disconnect();
      }
    });
    observer.observe(document.documentElement, { attributes: true, attributeFilter: ['class'] });
  } else {
    setTimeout(showHintIfReady, 500);
  }
}

})();
